"""Writes vanilla entity model layers as Rust tables for pomme-client.

usage: python -I export_models.py ENTITY_MODELS_JSON OUT_RS LAYER...

ENTITY_MODELS_JSON is a model-layer export made by running the game's own
`LayerDefinitions` over the player's installed client (Horizon's preparer
writes one as `entity-models.json`): per layer, a tree of parts, each with
its `PartPose` (x, y, z, xRot, yRot, zRot, xScale, yScale, zScale), its baked
polygons (four corners of x, y, z, u, v in model pixels and sheet fractions)
and their normals. LAYER is a key such as `minecraft:vex#main`; each becomes
a static named after it (`VEX`, `PIGLIN_BRUTE`, `ARMOR_STAND_SMALL`).

Parts are listed depth first, so a parent always precedes its children; the
layer's own root is not a part.
"""
import json
import sys


def const_name(layer):
    name = layer.split(':', 1)[1].split('#', 1)
    base = name[0].upper()
    return base if name[1] == 'main' else f'{base}_{name[1].upper()}'


def fmt(x):
    s = repr(float(x))
    return s if '.' in s or 'e' in s else s + '.0'


def parts_of(root):
    out = []

    def walk(name, part, parent):
        index = len(out)
        out.append((name, parent, part))
        for child_name, child in part['children'].items():
            walk(child_name, child, index)

    for name, child in root['children'].items():
        walk(name, child, None)
    return out


def main():
    src, dst, *layers = sys.argv[1:]
    models = json.load(open(src, encoding='utf-8'))
    lines = [
        '//! Vanilla entity model layers, generated by tools/entitygen/export_models.py',
        '//! from a `LayerDefinitions` export of the installed client. Do not edit.',
        '',
        "// Some layers only back tests; the numbers are vanilla's, pi-like or not.",
        '#![allow(dead_code, clippy::approx_constant, clippy::excessive_precision)]',
        'use super::exported::{ExportedPart, ExportedQuad};',
        '',
    ]
    for layer in layers:
        lines.append(f'/// `{layer}`.')
        lines.append(f'pub(crate) static {const_name(layer)}: &[ExportedPart] = &[')
        for name, parent, part in parts_of(models[layer]):
            pose = ', '.join(fmt(v) for v in part['pose'])
            parent = 'None' if parent is None else f'Some({parent})'
            lines.append('    ExportedPart {')
            lines.append(f'        name: "{name}",')
            lines.append(f'        parent: {parent},')
            lines.append(f'        pose: [{pose}],')
            lines.append('        quads: &[')
            for corners, normal in zip(part['polygons'], part['normals']):
                cs = ', '.join('[' + ', '.join(fmt(v) for v in c) + ']' for c in corners)
                n = ', '.join(fmt(v) for v in normal)
                lines.append(f'            ExportedQuad {{ normal: [{n}], corners: [{cs}] }},')
            lines.append('        ],')
            lines.append('    },')
        lines.append('];')
        lines.append('')
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))


main()
